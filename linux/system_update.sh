#!/bin/bash
# ==============================================================================
# system_update.sh — полное обновление системы (Ubuntu/Debian)
# Обновляет пакеты, чистит кэш и сообщает, требуется ли перезагрузка.
# Требует прав root (sudo)
# ==============================================================================

set -euo pipefail

if [ "$EUID" -ne 0 ]; then
  echo "Пожалуйста, запустите с sudo: sudo $0"
  exit 1
fi

echo "=== Обновление списка пакетов ==="
apt update

echo "=== Обновление установленных пакетов ==="
apt upgrade -y

echo "=== Удаление ненужных пакетов и кэша ==="
apt autoremove -y
apt clean

echo "=== Готово! ==="
if [ -f /var/run/reboot-required ]; then
  echo "ВНИМАНИЕ: требуется перезагрузка системы (обновлено ядро или системные библиотеки)."
else
  echo "Перезагрузка не требуется."
fi
